                <p>The Middle Years Programme (MYP) is a five-year programme for students aged from 11 to 16. Students at
                this stage are in a critical phase of personal and intellectual development. This is a time of
                uncertainty, sensitivity, resistance and questioning. The International Baccalaureate has set up the
                Middle Years Programme to meet students` academic needs and also help students develop a personal value
                system to guide their own lives. The 3 fundamental concepts of MYP are holistic learning, intercultural
                awareness and communication. The MYP provides a holistic international programme of study designed to meet
                the educational requirements of students aged 11-16. It is a broad-based curriculum framework which
                encourages students to question, evaluate and to think critically and independently. The programme offers
                an education that is skill-based, challenging, creative and flexible and requires a great deal of
                discipline. It also fosters understanding among young people around the world. The programme involves a
                vigorous and thorough study of various disciplines, emphasizing interdisciplinary study. Concurrently, the
                MYP also respects the independence and integrity of each discipline as students prepare for further study
                in the various subjects.</p>
